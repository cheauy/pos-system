const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('./helpers/pglite.cjs');
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
const [B,L,D,U,P,T,I,Q] = [1,2,3,4,5,6,7,8].map(id);
(async()=>{
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.user',true),'')::uuid$$;`);
    for(const table of JSON.parse(fs.readFileSync('tests/fixtures/branch-catalog-tables.json'))){
      await db.exec(`create table ${table.name}(${table.columns});`);
      if(table.columns.startsWith('id uuid,')) await db.exec(`alter table ${table.name} add primary key(id); alter table ${table.name} alter column id set default gen_random_uuid();`);
    }
    await db.exec(`alter table product_location_stock add primary key(location_id,product_id);
      alter table stock_transfers add foreign key(business_id) references businesses(id) on delete cascade;
      alter table stock_transfer_items add foreign key(transfer_id) references stock_transfers(id) on delete cascade;
      create function tenh_request_branch(uuid) returns uuid language sql as $$select current_setting('test.branch')::uuid$$;
      create function tenh_assert_effective_permission(uuid,text) returns void language plpgsql as $$begin if current_setting('test.denied',true)='yes' then raise exception 'Denied';end if;end$$;
      create function tenh_assert_plan_branch(uuid,uuid) returns void language plpgsql as $$begin if current_setting('test.expired',true)='yes' then raise exception 'Expired';end if;end$$;
      insert into businesses(id,name) values('${B}','Test');
      insert into business_locations(id,business_id,is_active,plan_disable_pending) values('${L}','${B}',true,false),('${D}','${B}',true,false);
      insert into products(id,business_id,name,is_active,stock_quantity) values('${P}','${B}','Shirt',true,10),('${Q}','${B}','Other',true,1);
      insert into product_location_stock(business_id,location_id,product_id,quantity) values('${B}','${L}','${P}',7),('${B}','${D}','${P}',3),('${B}','${L}','${Q}',1);
      insert into stock_transfers(id,business_id,source_location_id,destination_location_id,status,updated_at) values('${T}','${B}','${L}','${D}','draft','2026-09-27T00:00:00Z');
      insert into stock_transfer_items(id,business_id,transfer_id,product_id,quantity) values('${I}','${B}','${T}','${P}',2);
      select set_config('test.user','${U}',false),set_config('test.branch','${L}',false);`);
    const migration=fs.readFileSync('supabase/migrations/20260927003000_mobile_transfer_actions.sql','utf8');
    await db.exec(migration); await db.exec(migration);
    const version=()=>db.query('select updated_at::text version from stock_transfers where id=$1',[T]).then(r=>r.rows[0].version);
    const call=async(action='send',branch=L,items=[{productId:P,quantity:2}],expected)=>(await db.query('select tenh_mobile_transfer_action($1,$2,$3,$4,$5,$6::jsonb) result',[B,branch,T,action,expected ?? await version(),JSON.stringify(items)])).rows[0].result;
    const stock=async()=> (await db.query('select location_id,product_id,quantity from product_location_stock order by location_id,product_id')).rows;
    const initial=await stock();
    assert.deepEqual(await call('check'),{ready:true});
    await assert.rejects(call('send',D),/operating branch/);
    await assert.rejects(call('receive'),/destination/);
    await assert.rejects(call('send',L,[{productId:P,quantity:3}]),/items changed/);
    await assert.rejects(call('send',L,undefined,'2026-01-01Z'),/changed/);
    await db.exec("select set_config('test.denied','yes',false)"); await assert.rejects(call(),/Denied/);
    await db.exec("select set_config('test.denied','no',false); select set_config('test.expired','yes',false)"); await assert.rejects(call(),/Expired/);
    await db.exec("select set_config('test.expired','no',false); select set_config('test.user','',false)"); await assert.rejects(call(),/Sign in/);
    await db.exec(`select set_config('test.user','${U}',false); update products set is_active=false where id='${P}'`); await assert.rejects(call(),/Product not found/);
    await db.exec(`update products set is_active=true where id='${P}'; insert into stock_transfer_items(business_id,transfer_id,product_id,quantity) values('${B}','${T}','${Q}',2)`);
    await assert.rejects(call('send',L,[{productId:P,quantity:2},{productId:Q,quantity:2}]),/Not enough stock/);
    assert.deepEqual(await stock(),initial,'failure on second item rolls back first item');
    await db.exec(`delete from stock_transfer_items where product_id='${Q}'`);
    assert.equal((await call()).status,'in_transit');
    assert.equal((await call()).alreadyApplied,true);
    assert.equal((await stock()).find(r=>r.location_id===L&&r.product_id===P).quantity,5);
    await assert.rejects(db.exec(`update stock_transfer_items set quantity=3 where id='${I}'`),/Only draft/);
    await assert.rejects(db.exec(`insert into stock_transfer_items(business_id,transfer_id,product_id,quantity) values('${B}','${T}','${Q}',1)`),/Only draft/);
    await assert.rejects(db.exec(`delete from stock_transfer_items where id='${I}'`),/Only draft/);
    await assert.rejects(db.exec(`update stock_transfers set status='draft' where id='${T}'`),/reopened/);
    await assert.rejects(db.exec(`update stock_transfers set status=null where id='${T}'`),/reopened/);
    await assert.rejects(db.exec(`update stock_transfers set destination_location_id='${L}' where id='${T}'`),/branches/);
    await assert.rejects(db.exec(`delete from stock_transfers where id='${T}'`),/Only draft/);
    await db.exec(`select set_config('test.branch','${D}',false)`);
    assert.equal((await call('receive',D)).status,'received');
    assert.equal((await call('receive',D)).alreadyApplied,true);
    const final=await stock();
    assert.equal(final.find(r=>r.location_id===D&&r.product_id===P).quantity,5);
    assert.equal(final.filter(r=>r.product_id===P).reduce((sum,r)=>sum+r.quantity,0),10);
    assert.equal((await db.query('select stock_quantity from products where id=$1',[P])).rows[0].stock_quantity,10);
    await assert.rejects(db.exec(`update stock_transfers set status='in_transit' where id='${T}'`),/reopened/);
    assert.equal((await db.query("select has_function_privilege('anon','tenh_mobile_transfer_action(uuid,uuid,uuid,text,timestamptz,jsonb)','EXECUTE') allowed")).rows[0].allowed,false);
    await db.exec(`delete from businesses where id='${B}'`);
    assert.equal((await db.query('select count(*)::int n from stock_transfer_items')).rows[0].n,0,'business cascade preserved');
    console.log('PASS: transfer send/receive replay, branch/permission checks, stale items/version, atomic rollback, forward-only guards, stock conservation and business deletion cascade.');
  }finally{await db.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
